/**
 * 解读红线守卫（ADR 0001 第二道闸）—— 确定性、fail-closed。
 *
 * ## 为什么是「归一化 + 槽位」而不是「逐字正则」
 *
 * 2026-11-02 交叉对抗审查实测：逐字正则对平凡变体**完全不设防** ——
 * 一个全角冒号（`建议：买入`）、一个词内空格（`建 议买入`）、一句英文（`buy zone 17.8`）
 * 就能整体绕过。实测 8/8 逃逸（回归固化在 `test/guard.test.ts`）。
 *
 * 故本守卫改为两步：
 *   ① **归一化**：去全部空白、全角→半角、大写→小写、常见分隔符→无 ——
 *      让「同一个意思的不同写法」先收敛成同一个串；
 *   ② **槽位匹配**：在归一化后的串上匹配「动作槽位」（买入/卖出/仓位/目标价/预测…），
 *      并对高危组合（建议类副词 + 动作槽位）要求**共现**。
 *
 * ## 残余风险（诚实标注，不假装全覆盖）
 *
 * 归一化 + 槽位能挡住**已知的平凡变体**，但挡不住：
 * - 换一种没进槽位表的说法（例：「拿住这个位置」「有肉可吃」）；
 * - 拼音/方言（`jianyi mairu`）；
 * - 隐含建议（不给动作、只给强烈倾向，如「该票明显强于大盘，值得重点关注」）。
 *
 * 故：**词表不是唯一防线**，而是「最后一道确定性闸」；
 * 第一道防线是**素材约束**（模型只看得到确定性素材、无自由输入），
 * 第三道是**人工可核验**（素材逐项展示，用户能发现解读与数据不符）。
 * ⚠ 任何「守卫充分」的说法都不成立（见 `docs/adr/0001-ai-explain-redline.md` 的修订）。
 */

/** 归一化：去空白 + 全角转半角 + 大写转小写 + 去常见分隔符。 */
export function normalize(text: string): string {
  let s = text.normalize("NFKC"); // 全角 → 半角（含全角字母、标点）
  s = s.toLowerCase();
  // 去掉所有空白（含中文之间的空格）与常见分隔符：让「建 议买入」≡「建议买入」
  s = s.replace(/[\s\u3000]+/g, "");
  s = s.replace(/[，,。.、;；:：!！?？'"“”‘’()（）\[\]【】<>《》|]/g, "");
  return s;
}

/** 动作槽位：买卖/仓位/价格/止损止盈。命中任一即视为高危词。 */
const ACTION_SLOTS = [
  "买入", "卖出", "加仓", "减仓", "建仓", "清仓", "补仓", "抄底", "追高", "抛售", "出货", "入场", "离场",
  "买点", "卖点", "介入", "布局", "持有", "加码",
  "目标价", "目标位", "合理价", "估值位", "价位",
  "止损", "止盈", "止损位", "止盈位",
  "仓位", "轻仓", "半仓", "重仓", "满仓", "空仓", "底仓", "补仓",
  "buy", "sell", "long", "short", "stop", "targetprice",
];

/** 建议类副词：与动作槽位**共现**才算红线（避免单独出现「持有」就误杀）。 */
const ADVICE_MARKERS = [
  "建议", "推荐", "应该", "可以买", "值得", "不妨", "务必", "建议立刻",
  "suggest", "recommend", "should",
];

/** 预测类措辞：单独出现即拒答（模型预测涨跌本身就是越界，本项目不给预测）。 */
const PREDICTION_SLOTS = [
  "大概率", "必涨", "稳赚", "翻倍", "看多", "看涨", "看跌", "会涨", "会跌",
  "将上涨", "将下跌", "预计涨", "预计跌", "冲高", "回调就是",
  "risk-reward", "upside", "downside",
];

/** 拒答文案（用户可见，不含任何建议内容）。 */
export const REFUSAL =
  "该解读触及投资建议红线（如买入/卖出、目标价、仓位、止损或涨跌预测等），已按纪律整段拦下，不对外输出。" +
  "本系统只提供信号含义与数据解读，不构成任何投资建议。";

/**
 * 是否触红线。
 *
 * 判定顺序：
 * 1. 归一化；
 * 2. 预测类措辞 → 拒答（单槽位即判）；
 * 3. 动作槽位 **且** 出现建议类副词 → 拒答；
 * 4. 强动作槽位（买入/卖出/目标价/止损/仓位…）单独出现 → 拒答。
 *
 * ⚠ 第 4 条是「宁可误杀」的选择：本系统的合法解读里几乎不会出现这些词，
 *   而漏放的代价是把投资建议推给用户。
 */
export function isRedlined(text: string): boolean {
  const s = normalize(text);
  if (!s) return false;

  for (const p of PREDICTION_SLOTS) {
    if (s.includes(p)) return true;
  }

  const hasAction = ACTION_SLOTS.some((p) => s.includes(p));
  if (!hasAction) return false;

  const hasMarker = ADVICE_MARKERS.some((p) => s.includes(p));
  if (hasMarker) return true;

  // 强动作槽位：单独出现即拒答。
  // ⚠ 「持有」这类弱动作不在此列（单独出现可能是描述「该票持有史」），只在有副词时判红线。
  const STRONG = [
    "买入", "卖出", "加仓", "减仓", "建仓", "清仓", "抄底", "追高", "抛售", "出货", "入场", "离场",
    "买点", "卖点", "介入", "加码",
    "目标价", "目标位", "合理价", "估值位", "价位",
    "止损", "止盈",
    "仓位", "轻仓", "半仓", "重仓", "满仓", "空仓", "底仓",
    "buy", "sell", "long", "short", "stop", "targetprice",
  ];
  return STRONG.some((p) => s.includes(p));
}
