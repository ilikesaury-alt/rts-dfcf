# scanner/config_historical.py — 「v1 回捞」独立区配置（2026-09-16 新增）
# 定义集中在此，由 scanner/config.py 统一 re-export，保持 `from scanner.config import ...` 导入路径不变。
#
# 本区回答的问题与 v1 池选区**不同**：
#   v1 池选问「今天榜上哪只明天可能大涨」——候选是**今日在榜票**，引擎读当日榜单形态。
#   本区问「前几日进过 v1 的票，今天回调到位了吗」——候选是**前 N 个交易日的 v1 产出**，
#   引擎只读价格/量能，不读今日榜单上下文。
# 两者样本域互不重叠（本区默认排除今日已推荐票），故同屏展示不会出现同一只票两种结论。

import os

from scanner.config_categories import MAX_STOCK_PRICE, YI  # noqa: F401 (价格门/市值单位复用主线单源)
from scanner.config_sources import FUND_OUTFLOW_NET_PCT  # noqa: F401 (资金流出阈值单源)

# ── 开关 ────────────────────────────────────────────────────────────────────
HIST_WATCH_ENABLED = os.environ.get("RTS_HIST_WATCH", "1") != "0"

# ── 候选域 ──────────────────────────────────────────────────────────────────
# 回溯的**交易日数**（以「有 v1 产出的日期」计，非自然日）。取 2 是数据结论：
# 实测「距上次 v1 = 1 日」hit 8.6% / 2 日 6.0% / 3 日 5.3%（2691 样本，2026-06→09），
# 单调衰减——与「飙升榜效应半衰期 3~5 个交易日」一致。3 日以上衰减殆尽，纳入只会稀释。
HIST_LOOKBACK_DAYS = 2
# 排除「今日已被 v1/v2 推荐」的票：它已在 v1 池选区展示，再进本区是同屏重复选择。
HIST_EXCLUDE_TODAY_RECS = True
# 候选上限（成本控制）：仅用于截断批量行情请求，正常规模（前 2 日 v1 去重）约 20~50 只。
HIST_MAX_CANDIDATES = 120

# ── 硬门（必要条件，任一不过即剔除）────────────────────────────────────────
# 回调到位：今日涨幅 ≤ 该值。**这是本区的核心判据**——本区存在的理由正是
# 「榜上追高已晚，等回调」。实测深调档 hit 9.3%（vs 全池 6.9%）。
HIST_DIP_PCT = -3.0
# 承接有力：时间归一化量比 ≥ 该值（盘中按已过交易分钟投影为全天量能，见 trading_session）。
# **与项目其他低吸规则的「缩量」前提相反**，这是本区最重要的一条反直觉结论：
# 实测缩量档 hit 仅 4.3%（全部分档中最低），平量 8.1%、放量 7.7%。缩量回调在
# 本样本域里不是「惜售」而是「没人接」。既有的 comeback 回踩变体把「缩量」列为
# 6 维买点信号之一，与该实证冲突——本区不沿用那套信号，原因在此。
HIST_MIN_VOL_RATIO = 0.8
# 量比投影的已过分钟下界（分钟）。早盘量能分布极不均匀（开盘半小时量能占全天比重
# 远高于时间占比），线性投影会系统性高估；用下界把 09:30-10:00 的倍数压到 8x 以内。
HIST_MIN_ELAPSED_MIN = 30
# 量比分母（前 N 个交易日日均量）不足时该票不可判定 → 跳过（不按 0 处理，避免误杀）。
HIST_VOL_AVG_DAYS = 5

# ── 市值/价格门（与主线「小而美」同口径，但市值上限单独可调）───────────────
HIST_MAX_MARKET_CAP = 500 * YI  # 总市值上限：500 亿

# ── 评分（合计 100，**启发式排序键，未做样本外校准**）──────────────────────
# 硬门决定「进不进」，评分只决定「谁排前面」。权重按证据强弱分配：
# 回调深度（证据最直接）> 量能承接 > 距上次 v1 远近（实测 1 日/2 日差异很小）。
HIST_W_DIP = 50.0
HIST_W_VOL = 30.0
HIST_W_RECENCY = 20.0
# 回调深度的满分区间（%）：3%~8% 视为「回调到位且未破位」。
# 深于下界（BROKEN）线性衰减到 HIST_DIP_BROKEN_FLOOR——深跌往往意味着趋势已破，
# 本区要的是回调不是接刀。
HIST_DIP_IDEAL_LOW = -8.0
HIST_DIP_BROKEN = -15.0
HIST_DIP_BROKEN_FLOOR = 0.3
# 量比满分基准（量比 ≥ 该值给满分，防巨量出货：超过不再加分）。
HIST_VOL_FULL = 2.0
# 距上次 v1 = 1 个交易日满分，2 个交易日按该系数衰减。
HIST_RECENCY_DECAY = 0.5

# ── 展示 ────────────────────────────────────────────────────────────────────
HIST_DISPLAY_TOP = 8  # 终端最多展示条数
